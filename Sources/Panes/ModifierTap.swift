import AppKit
import HotkeyKit

/// Watches every modifier change and key press for the grid on hold ⌥⌘.
/// It never takes a key: every event passes on unchanged.
///
/// Its own `CGEventTap` rather than HotkeyKit's: `HotkeyTap` listens to
/// keyDown, keyUp and media keys only, never `flagsChanged`.
final class ModifierTap {
    var onModifiers: (Modifiers) -> Void = { _ in }
    var onAnyKeyDown: () -> Void = {}

    private var tap: CFMachPort?
    private var source: CFRunLoopSource?

    var isRunning: Bool { tap != nil }

    @discardableResult
    func start() -> Bool {
        guard tap == nil else { return true }
        let mask: CGEventMask = (1 << CGEventType.keyDown.rawValue) | (1 << CGEventType.flagsChanged.rawValue)
        let refcon = Unmanaged.passUnretained(self).toOpaque()
        guard let port = CGEvent.tapCreate(tap: .cgSessionEventTap, place: .headInsertEventTap, options: .defaultTap,
                                           eventsOfInterest: mask, callback: { _, type, event, refcon in
            guard let refcon else { return Unmanaged.passUnretained(event) }
            return Unmanaged<ModifierTap>.fromOpaque(refcon).takeUnretainedValue().handle(type, event)
        }, userInfo: refcon) else { return false }
        tap = port
        let src = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, port, 0)
        source = src
        CFRunLoopAddSource(CFRunLoopGetMain(), src, .commonModes)
        CGEvent.tapEnable(tap: port, enable: true)
        return true
    }

    func stop() {
        if let tap {
            CGEvent.tapEnable(tap: tap, enable: false)
            CFMachPortInvalidate(tap)
        }
        if let source { CFRunLoopRemoveSource(CFRunLoopGetMain(), source, .commonModes) }
        tap = nil
        source = nil
    }

    private func handle(_ type: CGEventType, _ event: CGEvent) -> Unmanaged<CGEvent>? {
        switch type {
        case .tapDisabledByTimeout, .tapDisabledByUserInput:
            if let tap { CGEvent.tapEnable(tap: tap, enable: true) }
        case .flagsChanged:
            onModifiers(Modifiers(cgFlags: event.flags))
        case .keyDown:
            onAnyKeyDown()
        default:
            break
        }
        return Unmanaged.passUnretained(event)
    }
}
